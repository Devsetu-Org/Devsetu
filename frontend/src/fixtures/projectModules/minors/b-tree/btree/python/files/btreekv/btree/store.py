"""PageIO: everything the tree needs from the layer below it."""

from __future__ import annotations

from typing import Protocol


class PageIO(Protocol):
    """*pager.Pager implements it; so do the txn and buffer pool later."""

    def read_page(self, no: int, buf: bytearray) -> None: ...
    def write_page(self, no: int, buf: bytes | bytearray) -> None: ...
    def allocate(self) -> int: ...
    def free(self, no: int) -> None: ...
    def root(self) -> int: ...
    def set_root(self, no: int) -> None: ...
